"""Transactional, idempotent, re-runnable import of one Olist/Amazon staging
batch (built by data/external_raw/build_olist_sample.py) into the V2
PostgreSQL schema (001_v2_transactional_and_observability_layer.sql).

Whole-batch semantics: everything happens in ONE transaction. Any file
parse error, any FK the import-time validation can't satisfy, any post-
import consistency check failure, or any row whose id already exists with
DIFFERENT content -- aborts the entire batch with ROLLBACK. Nothing is
committed unless every check passes.

Per-row insert semantics (never a silent ON CONFLICT DO NOTHING):
    id not present in DB           -> INSERT
    id present, content identical  -> SKIP (re-running the same batch is a no-op)
    id present, content differs    -> FAIL the whole batch

This script never touches the 27 hand-built fixture rows (they don't carry
this batch's -RW- id namespace and are never referenced here), and it never
writes to service_requests / decision_records / risk_assessments / refunds /
etc. -- it only populates the transaction fact layer plus data_provenance
for that layer. No decisions, risk assessments, or refunds are generated by
this script.

Usage:
    python db/migrations/import_olist_batch.py --dry-run
    python db/migrations/import_olist_batch.py
    python db/migrations/import_olist_batch.py --validate-only
    python db/migrations/import_olist_batch.py --batch-id ... --anchor-date 2026-08-31 --source-dir data/external_raw
"""

import argparse
import hashlib
import json
import os
import sys
from datetime import date
from decimal import Decimal
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_SOURCE_DIR = REPO_ROOT / "data" / "external_raw"


class BatchImportError(Exception):
    """Raised for any condition that must abort the whole transaction."""


def sha256_of_file(path: Path) -> str:
    h = hashlib.sha256()
    h.update(path.read_bytes())
    return h.hexdigest()


def load_json(path: Path):
    if not path.exists():
        raise BatchImportError(f"missing required source file: {path}")
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise BatchImportError(f"invalid JSON in {path}: {exc}") from exc


def normalize(value):
    """Make DB-returned and JSON-sourced values comparable regardless of
    Decimal/float/str-date/dict-vs-JSONB-string representation differences."""
    if value is None:
        return None
    if isinstance(value, (Decimal, float)):
        return round(float(value), 2)
    if isinstance(value, date):
        return value.isoformat()
    if isinstance(value, bool):
        return value
    if isinstance(value, (dict, list)):
        return json.dumps(value, sort_keys=True)
    if isinstance(value, str):
        stripped = value.strip()
        if stripped[:1] in ("{", "["):
            try:
                return json.dumps(json.loads(stripped), sort_keys=True)
            except json.JSONDecodeError:
                return value
    return value


def upsert_row(cursor, table: str, pk_col: str, row: dict, compare_cols: list[str], counters: dict):
    """INSERT if the pk doesn't exist; SKIP if it exists with identical
    content on compare_cols; raise BatchImportError if it exists with
    different content. Mutates counters[table] with inserted/skipped counts.
    """
    pk_val = row[pk_col]
    cursor.execute(f"SELECT {', '.join(compare_cols)} FROM {table} WHERE {pk_col} = %s", (pk_val,))
    existing = cursor.fetchone()
    counters.setdefault(table, {"inserted": 0, "skipped": 0})

    if existing is None:
        columns = list(row.keys())
        placeholders = ", ".join(["%s"] * len(columns))
        cursor.execute(
            f"INSERT INTO {table} ({', '.join(columns)}) VALUES ({placeholders})",
            [row[c] for c in columns],
        )
        counters[table]["inserted"] += 1
        return "inserted"

    for col in compare_cols:
        db_val = normalize(existing[col] if isinstance(existing, dict) else getattr(existing, col, None))
        new_val = normalize(row.get(col))
        if db_val != new_val:
            raise BatchImportError(
                f"{table}.{pk_col}={pk_val!r} already exists with different {col!r}: "
                f"db={db_val!r} vs import={new_val!r} -- aborting whole batch"
            )
    counters[table]["skipped"] += 1
    return "skipped"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true", help="run everything, then ROLLBACK instead of COMMIT")
    parser.add_argument("--batch-id", default=None, help="override the import_batch_id (default: from _meta.json)")
    parser.add_argument("--anchor-date", default=None, help="override dataset_anchor_date (default: from _meta.json)")
    parser.add_argument("--source-dir", default=str(DEFAULT_SOURCE_DIR), help="directory holding new_*.json + _meta.json")
    parser.add_argument("--validate-only", action="store_true", help="skip import, only run post-import consistency checks against what's already in the DB for this batch")
    args = parser.parse_args()

    database_url = os.getenv("DATABASE_URL", "").strip()
    if not database_url:
        print("DATABASE_URL is not set -- refusing to run", file=sys.stderr)
        return 1

    source_dir = Path(args.source_dir)
    meta = load_json(source_dir / "_meta.json")[0]
    batch_id = args.batch_id or meta["import_batch_id"]
    anchor_date = args.anchor_date or meta["dataset_anchor_date"]
    pipeline_version = meta["pipeline_version"]

    print(f"batch_id={batch_id}  anchor_date={anchor_date}  pipeline_version={pipeline_version}")
    print(f"source_dir={source_dir}  dry_run={args.dry_run}  validate_only={args.validate_only}")

    import psycopg
    from psycopg.rows import dict_row

    with psycopg.connect(database_url, row_factory=dict_row) as conn:
        conn.autocommit = False
        cur = conn.cursor()

        try:
            if not args.validate_only:
                _run_import(cur, source_dir, batch_id, anchor_date, pipeline_version)

            failures = _run_validation(cur, batch_id, anchor_date, source_dir)

            if failures:
                print("\n=== VALIDATION FAILED ===")
                for f in failures:
                    print(f"  ✗ {f}")
                conn.rollback()
                print("\nROLLED BACK -- nothing committed.")
                return 1

            print("\n=== ALL VALIDATIONS PASSED ===")
            if args.dry_run or args.validate_only:
                conn.rollback()
                print("dry-run/validate-only: ROLLED BACK (no changes persisted).")
            else:
                conn.commit()
                print("COMMITTED.")
            return 0

        except BatchImportError as exc:
            conn.rollback()
            print(f"\n=== IMPORT ABORTED ===\n  {exc}\nROLLED BACK -- nothing committed.", file=sys.stderr)
            return 1


def _checksum_manifest(source_dir: Path, filenames: list[str]) -> dict:
    return {name: sha256_of_file(source_dir / name) for name in filenames if (source_dir / name).exists()}


def _run_import(cur, source_dir: Path, batch_id: str, anchor_date: str, pipeline_version: str):
    counters: dict = {}

    source_files = [
        "new_customers.json", "new_products.json", "new_orders.json",
        "new_order_items.json", "new_payments.json", "new_shipments.json",
        "new_logistics.json",
    ]
    checksums = _checksum_manifest(source_dir, source_files)

    customers = load_json(source_dir / "new_customers.json")
    products = load_json(source_dir / "new_products.json")
    orders = load_json(source_dir / "new_orders.json")
    order_items = load_json(source_dir / "new_order_items.json")
    payments = load_json(source_dir / "new_payments.json")
    shipments = load_json(source_dir / "new_shipments.json")
    shipment_events = load_json(source_dir / "new_logistics.json")

    row_counts = {
        "customers": len(customers), "products": len(products), "orders": len(orders),
        "order_items": len(order_items), "payments": len(payments),
        "shipments": len(shipments), "shipment_events": len(shipment_events),
    }

    # -- 1. import_batches --
    batch_row = {
        "import_batch_id": batch_id,
        "pipeline_version": pipeline_version,
        "dataset_anchor_date": anchor_date,
        "source_datasets": json.dumps(["Olist Brazilian E-Commerce (Kaggle)", "Amazon Reviews 2023 (McAuley Lab, Hugging Face)"]),
        "row_counts": json.dumps(row_counts),
        "notes": json.dumps({"source_file_checksums": checksums}),
    }
    upsert_row(cur, "import_batches", "import_batch_id", batch_row,
               ["pipeline_version", "dataset_anchor_date", "row_counts"], counters)

    # -- 2. customers --
    for c in customers:
        row = {
            "customer_id": c["customer_id"], "source_unique_id": c["source_unique_id"],
            "vip_level": c["vip_level"],
            "register_date": c["register_date"],
            "canceled_order_count": c["canceled_order_count"],
            "import_batch_id": batch_id,
        }
        upsert_row(cur, "customers", "customer_id", row,
                   ["source_unique_id", "vip_level", "register_date", "canceled_order_count", "import_batch_id"],
                   counters)
        _provenance(cur, "customer", c["customer_id"], "source_unique_id", "REAL",
                    pipeline_version=pipeline_version, source_dataset="olist_customers_dataset.csv")
        _provenance(cur, "customer", c["customer_id"], "vip_level", "SYNTHETIC_ENRICHMENT",
                    pipeline_version=pipeline_version)
        _provenance(cur, "customer", c["customer_id"], "canceled_order_count", "DERIVED",
                    pipeline_version=pipeline_version,
                    transformation="count of this customer's other imported orders with order_status in (canceled, unavailable)")

    # -- 3. products --
    for p in products:
        row = {
            "product_id": p["product_id"], "category": p["category"], "price": p["price"],
            "is_fragile": p["is_fragile"], "is_customized": p["is_customized"],
            "import_batch_id": batch_id,
        }
        upsert_row(cur, "products", "product_id", row,
                   ["category", "price", "is_fragile", "is_customized", "import_batch_id"], counters)
        src = p.get("_source", {})
        _provenance(cur, "product", p["product_id"], None, "SYNTHETIC_ENRICHMENT",
                    pipeline_version=pipeline_version,
                    source_dataset="Amazon Reviews 2023", source_record_id=src.get("amazon_parent_asin"),
                    transformation=src.get("mapping_method"),
                    metadata=json.dumps({"amazon_title": src.get("amazon_title"),
                                         "amazon_category": src.get("amazon_category"),
                                         "reference_olist_price_cny": src.get("reference_olist_price_cny"),
                                         "price_band_applied": src.get("price_band_applied")}))
        _provenance(cur, "product", p["product_id"], "price", "DERIVED",
                    pipeline_version=pipeline_version, transformation=src.get("price_conversion"))

    # -- 4. orders --
    for o in orders:
        row = {
            "order_id": o["order_id"], "customer_id": o["customer_id"],
            "order_status": o["order_status"], "payment_status": o["payment_status"],
            "refund_status": o["refund_status"], "order_date": o["order_date"],
            "shipped_date": o["shipped_date"], "delivered_date": o["delivered_date"],
            "estimated_delivery_date": o["estimated_delivery_date"],
            "delivery_recipient_type": o["delivery_recipient_type"],
            "amount": o["amount"], "rounding_adjustment": o["rounding_adjustment"],
            "import_batch_id": batch_id,
        }
        upsert_row(cur, "orders", "order_id", row,
                   ["customer_id", "order_status", "order_date", "delivered_date", "amount", "import_batch_id"],
                   counters)
        for field in ("order_date", "shipped_date", "delivered_date", "estimated_delivery_date", "order_status"):
            _provenance(cur, "order", o["order_id"], field, "REAL",
                        pipeline_version=pipeline_version, source_dataset="olist_orders_dataset.csv",
                        transformation="timeline_shift")
        if o["refund_status"] is not None:
            _provenance(cur, "order", o["order_id"], "refund_status", "SYNTHETIC_ENRICHMENT",
                        pipeline_version=pipeline_version,
                        transformation="order_status=canceled/unavailable does NOT prove a refund occurred; "
                                       "this is a randomly-assigned plausible value, not an observed fact")
        _provenance(cur, "order", o["order_id"], "amount", "DERIVED",
                    pipeline_version=pipeline_version, transformation="BRL_to_CNY, rate=1.35 (approximate, not live FX)")

    # -- 5. order_items --
    for it in order_items:
        row = {
            "order_item_id": it["order_item_id"], "order_id": it["order_id"],
            "product_id": it["product_id"], "sku_id": it["sku_id"], "sku_name": it["sku_name"],
            "unit_price": it["unit_price"], "quantity": it["quantity"],
            "discount_amount": it["discount_amount"], "paid_amount": it["paid_amount"],
            "shipped_product_id": it["shipped_product_id"], "shipped_quantity": it["shipped_quantity"],
            "category": None, "import_batch_id": batch_id,
        }
        upsert_row(cur, "order_items", "order_item_id", row,
                   ["order_id", "product_id", "unit_price", "paid_amount", "import_batch_id"], counters)

    # -- 6. payments --
    for p in payments:
        row = {
            "payment_id": p["payment_id"], "order_id": p["order_id"],
            "payment_sequential": p["payment_sequential"], "amount": p["amount"],
            "currency": p["currency"], "payment_method": p["payment_method"],
            "payment_installments": p["payment_installments"],
            "payment_reference_date": p["payment_reference_date"],
            "import_batch_id": batch_id,
        }
        upsert_row(cur, "payments", "payment_id", row,
                   ["order_id", "payment_sequential", "amount", "payment_method", "import_batch_id"],
                   counters)
        # payment_sequential/payment_type/payment_installments/payment_value
        # are real Olist fields; payment_reference_date is NOT -- Olist's
        # payments CSV has no timestamp at all, so this is the order's
        # purchase date reused as a reference point, not an observed
        # payment-channel event time.
        _provenance(cur, "payment", p["payment_id"], None, "REAL",
                    pipeline_version=pipeline_version, source_dataset="olist_order_payments_dataset.csv")
        _provenance(cur, "payment", p["payment_id"], "payment_reference_date", "DERIVED",
                    pipeline_version=pipeline_version,
                    transformation="order's purchase date reused as a reference point -- "
                                   "Olist's payments dataset has no real payment timestamp")

    # -- 7. shipments --
    for s in shipments:
        row = {
            "shipment_id": s["shipment_id"], "order_id": s["order_id"], "carrier": s["carrier"],
            "shipped_at": s["shipped_at"], "delivered_at": s["delivered_at"],
            "estimated_delivery_date": s["estimated_delivery_date"],
            "shipment_status": s["shipment_status"], "import_batch_id": batch_id,
        }
        upsert_row(cur, "shipments", "shipment_id", row,
                   ["order_id", "shipment_status", "delivered_at", "import_batch_id"], counters)

    # -- 8. shipment_events (only for shipments with a real/derived exception) --
    for idx, ev in enumerate(shipment_events, start=1):
        row = {
            "event_id": f"SHPEVT-RW-{idx:05d}", "shipment_id": ev["shipment_id"],
            "event_type": ev["exception_type"], "event_time": ev["exception_recorded_date"],
            "resolved": ev["resolved"], "source_type": ev["source_type"], "derivation": ev["derivation"],
        }
        upsert_row(cur, "shipment_events", "event_id", row,
                   ["shipment_id", "event_type", "resolved"], counters)

    print("\n=== IMPORT COUNTS ===")
    for table, c in counters.items():
        print(f"  {table:16s} inserted={c['inserted']:5d}  skipped={c['skipped']:5d}")


def _provenance(cur, entity_type, entity_id, field_name, source_type, *,
                pipeline_version, source_dataset=None, source_record_id=None,
                transformation=None, metadata=None):
    """provenance_id is a UUID with no natural business key, so a plain
    INSERT would duplicate on every re-run of the batch. Skip if an
    equivalent claim (same entity/field/source_type/pipeline_version/
    transformation) already exists -- same "id exists with identical
    content -> skip" principle as upsert_row, just keyed on the tuple that
    actually identifies "the same claim" here instead of a single pk."""
    cur.execute(
        """
        SELECT 1 FROM data_provenance
        WHERE entity_type = %s AND entity_id = %s
          AND field_name IS NOT DISTINCT FROM %s
          AND source_type = %s
          AND pipeline_version IS NOT DISTINCT FROM %s
          AND transformation IS NOT DISTINCT FROM %s
        """,
        (entity_type, entity_id, field_name, source_type, pipeline_version, transformation),
    )
    if cur.fetchone() is not None:
        return
    cur.execute(
        """
        INSERT INTO data_provenance
            (entity_type, entity_id, field_name, source_type, source_dataset,
             source_record_id, transformation, pipeline_version, metadata)
        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)
        """,
        (entity_type, entity_id, field_name, source_type, source_dataset,
         source_record_id, transformation, pipeline_version, metadata),
    )


def _run_validation(cur, batch_id: str, anchor_date: str, source_dir: Path) -> list[str]:
    """Runs inside the same open transaction as the import, so it sees
    uncommitted rows. Returns a list of human-readable failure descriptions;
    empty list means everything passed."""
    failures: list[str] = []

    def check(sql: str, label: str, expect_zero=True):
        cur.execute(sql, (batch_id,))
        n = cur.fetchone()["n"]
        if expect_zero and n != 0:
            failures.append(f"{label}: {n} violating row(s)")
        return n

    # 1. every order has a customer that exists
    check("""SELECT count(*) n FROM orders o
             WHERE o.import_batch_id = %s
               AND NOT EXISTS (SELECT 1 FROM customers c WHERE c.customer_id = o.customer_id)""",
          "orders without a matching customer")

    # 2. every order_item resolves to an order and a product (soft-reference
    # check -- see migration notes on why this isn't a DB-level FK yet)
    check("""SELECT count(*) n FROM order_items oi
             WHERE oi.import_batch_id = %s
               AND NOT EXISTS (SELECT 1 FROM orders o WHERE o.order_id = oi.order_id)""",
          "order_items with no matching order (orphaned soft reference)")
    check("""SELECT count(*) n FROM order_items oi
             WHERE oi.import_batch_id = %s
               AND NOT EXISTS (SELECT 1 FROM products p WHERE p.product_id = oi.product_id)""",
          "order_items with no matching product (orphaned soft reference)")

    # 3. a given Amazon-sourced product_id never appears with two different
    # (category, price) pairs across the products table for this batch
    check("""SELECT count(*) n FROM (
                SELECT product_id FROM products WHERE import_batch_id = %s
                GROUP BY product_id HAVING count(DISTINCT category) > 1 OR count(DISTINCT price) > 1
             ) t""",
          "products with inconsistent category/price under the same product_id")

    # payment_sequential must not repeat within the same order
    check("""SELECT count(*) n FROM (
                SELECT p.order_id, p.payment_sequential FROM payments p
                JOIN orders o ON o.order_id = p.order_id
                WHERE o.import_batch_id = %s
                GROUP BY p.order_id, p.payment_sequential HAVING count(*) > 1
             ) t""",
          "orders with a repeated payment_sequential value")

    # 4. non-canceled, ever-shipped orders have a shipment row
    check("""SELECT count(*) n FROM orders o
             WHERE o.import_batch_id = %s AND o.order_status NOT IN ('canceled', 'unavailable')
               AND o.shipped_date IS NOT NULL
               AND NOT EXISTS (SELECT 1 FROM shipments s WHERE s.order_id = o.order_id)""",
          "shipped, non-canceled orders missing a shipment row")

    # 5. shipment timestamps are not out of order
    check("""SELECT count(*) n FROM shipments s JOIN orders o ON o.order_id = s.order_id
             WHERE o.import_batch_id = %s
               AND s.delivered_at IS NOT NULL AND s.shipped_at IS NOT NULL
               AND s.delivered_at < s.shipped_at""",
          "shipments with delivered_at before shipped_at")

    # 6. order amount reconciles with order_items + rounding_adjustment
    check("""SELECT count(*) n FROM (
                SELECT o.order_id, o.amount, o.rounding_adjustment,
                       COALESCE(SUM(oi.paid_amount), 0) AS item_sum
                FROM orders o LEFT JOIN order_items oi ON oi.order_id = o.order_id
                WHERE o.import_batch_id = %s
                GROUP BY o.order_id, o.amount, o.rounding_adjustment
             ) t
             WHERE ABS(t.amount - t.rounding_adjustment - t.item_sum) > 0.01""",
          "orders whose amount doesn't reconcile with order_items + rounding_adjustment")

    # 7. nothing lands after the scenario anchor date
    cur.execute("""SELECT count(*) n FROM orders WHERE import_batch_id = %s AND
                   (order_date > %s OR delivered_date > %s OR shipped_date > %s)""",
                (batch_id, anchor_date, anchor_date, anchor_date))
    n = cur.fetchone()["n"]
    if n != 0:
        failures.append(f"orders/shipments dated after scenario_as_of_time ({anchor_date}): {n} row(s)")

    cur.execute("""SELECT count(*) n FROM shipment_events se JOIN shipments s ON s.shipment_id = se.shipment_id
                   JOIN orders o ON o.order_id = s.order_id
                   WHERE o.import_batch_id = %s AND se.event_time > %s""", (batch_id, anchor_date))
    n = cur.fetchone()["n"]
    if n != 0:
        failures.append(f"shipment_events timestamped after scenario_as_of_time: {n} row(s)")

    # 8. every REAL/DERIVED/SYNTHETIC field this batch touched has a
    # data_provenance row (spot-check: every imported order and product has
    # at least one provenance row)
    check("""SELECT count(*) n FROM orders o WHERE o.import_batch_id = %s
             AND NOT EXISTS (SELECT 1 FROM data_provenance dp WHERE dp.entity_type='order' AND dp.entity_id=o.order_id)""",
          "orders with zero data_provenance rows")
    check("""SELECT count(*) n FROM products p WHERE p.import_batch_id = %s
             AND NOT EXISTS (SELECT 1 FROM data_provenance dp WHERE dp.entity_type='product' AND dp.entity_id=p.product_id)""",
          "products with zero data_provenance rows")

    # -- extra checks from the review --
    # row counts match the source JSON files exactly
    for table, filename in (("customers", "new_customers.json"), ("products", "new_products.json"),
                             ("orders", "new_orders.json"), ("order_items", "new_order_items.json"),
                             ("payments", "new_payments.json"), ("shipments", "new_shipments.json")):
        source_rows = load_json(source_dir / filename)
        cur.execute(f"SELECT count(*) n FROM {table} WHERE import_batch_id = %s", (batch_id,))
        db_n = cur.fetchone()["n"]
        if db_n != len(source_rows):
            failures.append(f"{table}: DB has {db_n} rows for this batch, source file has {len(source_rows)}")

    # delivered orders must have delivered_at on their shipment; canceled
    # orders must not have a delivery timestamp at all... except the
    # documented real-world exception (Olist orders that were shipped/
    # delivered before later being marked canceled) -- so this check only
    # flags orders that are BOTH canceled AND never shipped AND still show a
    # delivered_date, which would be a genuine impossibility.
    check("""SELECT count(*) n FROM orders WHERE import_batch_id = %s
             AND order_status IN ('canceled','unavailable')
             AND delivered_date IS NOT NULL AND shipped_date IS NULL""",
          "canceled/unavailable orders with a delivered_date but no shipped_date (impossible)")
    check("""SELECT count(*) n FROM orders WHERE import_batch_id = %s
             AND order_status = 'delivered' AND delivered_date IS NULL""",
          "orders marked delivered with no delivered_date")

    # price ratio still within [0.3, 3.0] -- re-derived from provenance metadata
    cur.execute("""SELECT entity_id, metadata FROM data_provenance
                   WHERE entity_type='product' AND field_name IS NULL AND pipeline_version IS NOT NULL
                     AND entity_id IN (SELECT product_id FROM products WHERE import_batch_id = %s)""",
                (batch_id,))
    out_of_band = 0
    for row in cur.fetchall():
        meta = row["metadata"]
        if not meta:
            continue
        meta = meta if isinstance(meta, dict) else json.loads(meta)
        band = meta.get("price_band_applied")
        ref = meta.get("reference_olist_price_cny")
        if band and ref:
            cur.execute("SELECT price FROM products WHERE product_id = %s", (row["entity_id"],))
            price = float(cur.fetchone()["price"])
            ratio = price / ref if ref else None
            if ratio is not None and not (band[0] <= ratio <= band[1]):
                out_of_band += 1
    if out_of_band:
        failures.append(f"products with mapped price outside the [0.3, 3.0] band: {out_of_band}")

    return failures


if __name__ == "__main__":
    raise SystemExit(main())
